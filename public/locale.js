export function selectLanguage(saved, preferred = '') {
  if (saved === 'en' || saved === 'zh-Hant') return saved;
  try {
    const locale = new Intl.Locale(preferred);
    if (locale.language === 'zh' &&
        (locale.script === 'Hant' ||
          (!locale.script && ['TW', 'HK', 'MO'].includes(locale.region)))) {
      return 'zh-Hant';
    }
  } catch {
    // Some browser environments may omit the locale.
  }
  return 'en';
}

export function translator(language) {
  return (key, values = {}) => {
    const sentence = strings[key]?.[language === 'zh-Hant' ? 1 : 0] ?? key;
    return sentence.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  };
}

export function labelName(label, t) {
  const defaults = ['favorite', 'gaming', 'podcast', 'web', 'essay', 'tutorial'];
  return !label.customName && defaults.includes(label.id) ? t(label.id) : label.name;
}
